#!/usr/bin/env node
// Regenerates REDIRECTS.md from lib/redirects.mjs.
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { REDIRECTS, GONE, GONE_PREFIXES } from "../lib/redirects.mjs";

// Every previously published path, taken from the last commit before the prune.
const OLD = "d7ed6e2";
const show = (f) => execFileSync("git", ["show", `${OLD}:${f}`], { encoding: "utf8" });
const slugs = (src) => [...src.matchAll(/^    slug: "([^"]+)"/gm)].map((m) => m[1]);
const fontSlugs = slugs(show("lib/pages.ts"));
const blogSlugs = slugs(show("lib/blog.ts"));
const sym = [...show("lib/symbols.ts").matchAll(/slug: "([^"]+)"/g)].map((m) => `/symbols/${m[1]}`);
const emo = [...show("lib/emoticons.ts").matchAll(/slug: "([^"]+)"/g)].map((m) => `/emoticons/${m[1]}`);
const names = [...show("lib/names.ts").matchAll(/slug: "([^"]+)"/g)].map((m) => `/name-generator/${m[1]}`);
const es = ["cursive", "fancy", "bold", "instagram"].map((s) => `/es/font-generator/${s}`).concat(["/es/font-generator", "/es/cool-symbols/hearts"]);
const keptBlog = new Set(["blackletter-gothic-fraktur-difference", "old-english-fonts-instagram-bio", "old-english-fonts-tattoo-guide", "how-unicode-fonts-actually-work", "best-old-english-fonts-for-discord"]);

const r301 = new Map(REDIRECTS.map((r) => [r.source, r.destination]));
const all = new Set([
  ...REDIRECTS.map((r) => r.source),
  ...GONE,
  ...fontSlugs.map((s) => `/font-generator/${s}`),
  ...blogSlugs.filter((s) => !keptBlog.has(s)).map((s) => `/blog/${s}`),
  ...sym, ...emo, ...names, ...es,
]);
const rows = [...all].sort().map((p) => {
  const dest = r301.get(p);
  const gone = !dest && (GONE.includes(p) || GONE_PREFIXES.some((x) => p.startsWith(x)));
  return `| \`${p}\` | ${dest ? `301 → \`${dest}\`` : gone ? "410 Gone" : "**unhandled**"} |`;
});
const n301 = rows.filter((r) => r.includes("301")).length;
const n410 = rows.filter((r) => r.includes("410")).length;
writeFileSync(
  "REDIRECTS.md",
  `# Removed URLs

Generated by \`node scripts/redirects-md.mjs\` from \`lib/redirects.mjs\`.
301s are served by \`next.config.mjs\`; 410s by \`proxy.ts\`.
Also: \`oldenglishfontgenerator.com/*\` → \`https://www.oldenglishfontgenerator.com/*\` (301), and trailing slashes are stripped (Next.js permanent redirect).

**${n301} redirected (301), ${n410} gone (410).**

| Old URL | Result |
|---|---|
${rows.join("\n")}
`
);
console.log(`REDIRECTS.md: ${n301} x 301, ${n410} x 410, ${rows.filter((r) => r.includes("unhandled")).length} unhandled`);
